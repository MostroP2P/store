// SEO (pure): the tags link previews and search engines read, built from catalog.json.
// Link previews (Telegram, WhatsApp, X, Nostr clients…) never run JavaScript, so a product only gets its own
// preview from a static page of its own: <id>.html, made from product.html, with that product's tags and image.

import { normalizeCatalog } from '../src/catalog.js';
import { localizeJson, DEFAULT_LANG } from '../src/i18n.js';
import { normalizeStoreConfig } from '../src/store/config.js';
import { storeProducts } from '../src/store/products.js';
import { moneyFormat } from '../src/store/money.js';

export const SITE_URL = 'https://store.mostro.network';
export const SITE_NAME = 'Mostro Store';
export const OG_IMAGE = Object.freeze({ width: 1200, height: 630 });
export const STORE_IMAGE = 'store';
const THEME_COLOR = '#8CC63F';
const TWITTER = '@MostroP2P';
const STORE_TITLE = 'Mostro Store · T-shirts';
const STORE_DESCRIPTION = 'Mostro T-shirts. Pay with Lightning; your details travel encrypted over Nostr.';
const PRODUCT_DESCRIPTION = 'A Mostro T-shirt. Pay with Lightning; your details travel encrypted over Nostr.';
const IN_STOCK = 'https://schema.org/InStock';
// Product pages live next to these, so an id may not take their names; nor the store's preview image's
const RESERVED_NAMES = Object.freeze(['index', 'product', 'checkout', 'viewer', '404', STORE_IMAGE]);
// Lowercase words joined by hyphens; never a leading hyphen, which a shell command would read as an option
const PAGE_ID = /^[a-z0-9][a-z0-9-]*$/;
const BLOCK_START = '<!-- SEO: generated by scripts/seo.mjs from catalog.json; do not edit by hand -->';
const BLOCK_END = '<!-- /SEO -->';
const BLOCK = /<!-- SEO: generated[^>]*-->[\s\S]*?<!-- \/SEO -->/;
const INDENT = '  ';

const ESCAPES = Object.freeze({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' });
export const escapeHtml = (text) => String(text).replace(/[&<>"']/g, (char) => ESCAPES[char]);

export const productPage = (id) => `${id}.html`;
export const ogImage = (name) => `assets/og/${name}.jpg`;
const absolute = (path) => `${SITE_URL}/${path}`;

const meta = (key, name, content) => `<meta ${key}="${name}" content="${escapeHtml(content)}">`;
// "</script>" inside the JSON would end the element early
const jsonLd = (data) => `<script type="application/ld+json">${JSON.stringify(data).replace(/</g, '\\u003c')}</script>`;

const PUBLISHER = Object.freeze({
  '@type': 'Organization',
  name: 'Mostro P2P',
  url: 'https://mostro.network',
  logo: { '@type': 'ImageObject', url: absolute('assets/mostro-logo.png') },
  sameAs: ['https://github.com/MostroP2P', 'https://t.me/MostroP2P'],
});

/**
 * Head tags of one page: description, canonical URL, Open Graph, Twitter card and JSON-LD.
 * page: { title, description, url (null: no canonical), image, imageAlt, type, extraMeta: [[property, content]],
 * descriptionAttrs, robots, data (JSON-LD) }
 */
export function headTags(page) {
  const description = `<meta name="description" content="${escapeHtml(page.description)}"${page.descriptionAttrs ?? ''}>`;
  return [
    description,
    ...(page.robots ? [meta('name', 'robots', page.robots)] : []),
    ...(page.url ? [`<link rel="canonical" href="${escapeHtml(page.url)}">`] : []),
    meta('name', 'theme-color', THEME_COLOR),
    meta('property', 'og:type', page.type),
    meta('property', 'og:site_name', SITE_NAME),
    meta('property', 'og:title', page.title),
    meta('property', 'og:description', page.description),
    ...(page.url ? [meta('property', 'og:url', page.url)] : []),
    meta('property', 'og:image', page.image),
    meta('property', 'og:image:width', OG_IMAGE.width),
    meta('property', 'og:image:height', OG_IMAGE.height),
    meta('property', 'og:image:alt', page.imageAlt),
    meta('property', 'og:locale', 'en_US'),
    meta('property', 'og:locale:alternate', 'es_AR'),
    ...(page.extraMeta ?? []).map(([property, content]) => meta('property', property, content)),
    meta('name', 'twitter:card', 'summary_large_image'),
    meta('name', 'twitter:site', TWITTER),
    meta('name', 'twitter:title', page.title),
    meta('name', 'twitter:description', page.description),
    meta('name', 'twitter:image', page.image),
    meta('name', 'twitter:image:alt', page.imageAlt),
    ...(page.data ? [jsonLd(page.data)] : []),
  ];
}

/** Replaces the marked SEO block of `html` with `tags`; fails when the page has no block. */
export function withSeoBlock(html, tags) {
  if (!BLOCK.test(html)) throw new Error('no SEO block (<!-- SEO: generated … --> … <!-- /SEO -->) in the page');
  const block = [BLOCK_START, ...tags, BLOCK_END].join(`\n${INDENT}`);
  return html.replace(BLOCK, () => block);
}

const storeTags = () => headTags({
  title: STORE_TITLE,
  description: STORE_DESCRIPTION,
  descriptionAttrs: ' data-i18n-attr="content:homeDescription"',
  url: `${SITE_URL}/`,
  type: 'website',
  image: absolute(ogImage(STORE_IMAGE)),
  imageAlt: 'Mostro T-shirts',
  data: {
    '@context': 'https://schema.org',
    '@type': 'WebSite',
    name: SITE_NAME,
    url: `${SITE_URL}/`,
    description: STORE_DESCRIPTION,
    inLanguage: ['en', 'es'],
    publisher: PUBLISHER,
  },
});

/** product.html with no id of its own: the store's preview, kept out of search results (every product has its page). */
const genericProductTags = () => headTags({
  title: STORE_TITLE,
  description: STORE_DESCRIPTION,
  robots: 'noindex',
  url: null,
  type: 'website',
  image: absolute(ogImage(STORE_IMAGE)),
  imageAlt: 'Mostro T-shirts',
});

function productTags(product, currency) {
  const url = absolute(productPage(product.id));
  const image = absolute(ogImage(product.id));
  const description = product.description ?? PRODUCT_DESCRIPTION;
  return headTags({
    title: `${product.name} · ${SITE_NAME}`,
    description,
    url,
    type: 'product',
    image,
    imageAlt: `${product.name} T-shirt`,
    extraMeta: [['product:price:amount', String(product.price)], ['product:price:currency', currency]],
    data: {
      '@context': 'https://schema.org',
      '@type': 'Product',
      name: product.name,
      description,
      image,
      url,
      brand: { '@type': 'Brand', name: 'Mostro' },
      offers: { '@type': 'Offer', price: String(product.price), priceCurrency: currency, availability: IN_STOCK, url },
    },
  });
}

function replaceOnce(html, from, to) {
  if (!html.includes(from)) throw new Error(`product.html no longer has ${from}`);
  return html.replace(from, () => to);
}

/** The page of one product: product.html with the product's id, title, text and tags. */
export function productHtml(template, product, currency) {
  const price = moneyFormat(DEFAULT_LANG, currency).price(product.price);
  const lead = product.description ?? '';
  return [
    ['<html lang="en">', `<html lang="en" data-product="${escapeHtml(product.id)}">`],
    ['<title data-i18n="productPageTitle">T-shirt · Mostro Store</title>', `<title>${escapeHtml(product.name)} · ${SITE_NAME}</title>`],
    ['<h1 class="product-title" id="product-name"></h1>', `<h1 class="product-title" id="product-name">${escapeHtml(product.name)}</h1>`],
    ['<p class="product-lead" id="product-lead" hidden></p>', `<p class="product-lead" id="product-lead"${lead ? '' : ' hidden'}>${escapeHtml(lead)}</p>`],
    ['<p class="price-box price-mono" id="product-price"></p>', `<p class="price-box price-mono" id="product-price">${escapeHtml(price)}</p>`],
  ].reduce((html, [from, to]) => replaceOnce(html, from, to), withSeoBlock(template, productTags(product, currency)));
}

/** sitemap.xml: the collection and every product page. */
export function sitemapXml(products) {
  const urls = [`${SITE_URL}/`, ...products.map((product) => absolute(productPage(product.id)))];
  return [
    '<?xml version="1.0" encoding="UTF-8"?>',
    '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">',
    ...urls.map((url) => `  <url><loc>${escapeHtml(url)}</loc></url>`),
    '</urlset>',
    '',
  ].join('\n');
}

/**
 * Products on sale, in English, from the raw catalog.json: { products, currency, catalog, config }.
 * Throws when the catalog or the store section is unusable.
 */
export function publishedProducts(rawCatalog) {
  const raw = localizeJson(rawCatalog, DEFAULT_LANG);
  const { catalog } = normalizeCatalog(raw);
  if (!catalog) throw new Error('catalog.json has errors: check it in viewer.html');
  const { config } = normalizeStoreConfig(raw.store, catalog.colors.map((color) => color.id));
  if (!config) throw new Error('catalog.json has no usable "store" section');
  const products = storeProducts(catalog, config);
  const unusable = products.filter((product) => RESERVED_NAMES.includes(product.id) || !PAGE_ID.test(product.id));
  if (unusable.length > 0) throw new Error(`these ids cannot name a page: ${unusable.map((p) => p.id).join(', ')}`);
  return { products, currency: config.currency, catalog, config };
}

/** Every file the SEO build writes: Map(path → content). `pages` holds the current index.html and product.html. */
export function seoFiles(rawCatalog, pages) {
  const { products, currency } = publishedProducts(rawCatalog);
  return new Map([
    ['index.html', withSeoBlock(pages['index.html'], storeTags())],
    ['product.html', withSeoBlock(pages['product.html'], genericProductTags())],
    ...products.map((product) => [productPage(product.id), productHtml(pages['product.html'], product, currency)]),
    ['sitemap.xml', sitemapXml(products)],
  ]);
}

/** Images the pages above need: the store's and one per product. */
export const ogImagesNeeded = (rawCatalog) => [STORE_IMAGE, ...publishedProducts(rawCatalog).products.map((product) => product.id)];

/** A product page this build made earlier (it carries data-product), to delete when the product is gone. */
export const isGeneratedProductPage = (html) => /<html lang="en" data-product="/.test(html);
